#!/usr/bin/env node
/**
 * gen-assets.mjs — bundles the portfolio's images into assets/img.js
 * as base64 data URIs.
 *
 * WHY: the portfolio must work when opened directly from disk (file://)
 * with zero server. Browsers taint <canvas> when it draws file:// images,
 * which breaks html2canvas PDF export. Data URIs are same-origin by
 * definition → export always works, offline, on any machine.
 *
 * Re-run after adding images:   node tools/gen-assets.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, "..");
const WORK = resolve(ROOT, "..", "public", "images", "work");

/** key → source path under public/images/work */
const MANIFEST = {
  avatar: "icon.png",

  // Code & Canvas — Platform (dev)
  "ccdev-thumb": "code-canvas-dev/cc-dev-thumb.jpg",

  // GAD Heart & Lungs Institute
  "gad-thumb": "gad/gad-thumb.jpg",
  "gad-mockup-logo": "gad/gad-mockup-logo.jpg",
  "gad-cover": "gad/gad-cover.png",
  "gad-logo-variations": "gad/gad-logo-variations.png",
  "gad-colors": "gad/gad-colors-primary.png",
  "gad-exhibition": "gad/gad-mockup-exhibition.jpg",
  "gad-signage": "gad/gad-signage-environmental.jpg",

  // Ahmed Bedeer
  "bedeer-thumb": "ahmed-bedeer-mockup.jpg",
  "bedeer-cover": "ahmed-bedeer-cover.jpg",
  "bedeer-logo": "ahmed-bedeer-logo.png",
  "bedeer-construction": "ahmed-bedeer-construction.png",
  "bedeer-applications": "ahmed-bedeer-applications.jpg",
  "bedeer-type": "ahmed-bedeer-type.png",

  // Nile Pharma Food
  "npf-thumb": "nile-pharma.jpg",
  "npf-img-a": "nile-pharma/npf-img-a.png",
  "npf-logo-grid": "nile-pharma/npf-logo-grid.png",
  "npf-waves": "nile-pharma/npf-logo-waves.jpg",
  "npf-proxeed": "nile-pharma/npf-proxeed-post.jpg",

  // Code & Canvas (studio identity)
  "cc-hero": "cc-logo-hero.jpg",
  "cc-cover": "cc-cover.jpg",
  "cc-manifesto": "cc-manifesto.png",
  "cc-icon-construction": "cc-icon-construction.png",
  "cc-wordmark": "cc-wordmark.png",
  "cc-variants": "cc-logo-variants.jpg",
  "cc-gradients": "cc-gradients.png",
  "cc-design-samples": "cc-design-samples.png",
  "cc-closing": "cc-closing.jpg",

  // Reflection
  "refl-thumb": "reflection/refl-thumb.jpg",
  "refl-cover": "reflection/refl-cover.png",
  "refl-anatomy": "reflection/refl-logo-anatomy.jpg",
  "refl-colors": "reflection/refl-colors.jpg",
  "refl-preview": "reflection/refl-preview.jpg",

  // Dev products with real thumbs
  "erp-thumb": "dev-cards/nile-erp-command-center-card.jpg",
  "zad-thumb": "zad-thumb.jpg",
  "farm-thumb": "farm-thumb.jpg",
};

const MIME = { jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png", webp: "image/webp" };

const entries = [];
let missing = 0;
for (const [key, rel] of Object.entries(MANIFEST)) {
  const abs = join(WORK, rel);
  try {
    const buf = readFileSync(abs);
    const ext = rel.split(".").pop().toLowerCase();
    const mime = MIME[ext] ?? "application/octet-stream";
    entries.push(`  ${JSON.stringify(key)}: "data:${mime};base64,${buf.toString("base64")}"`);
    console.log(`  ✓ ${key}  (${(buf.length / 1024).toFixed(0)} KB)`);
  } catch {
    missing++;
    console.warn(`  ✗ MISSING: ${rel}`);
  }
}

const out = `/* AUTO-GENERATED by tools/gen-assets.mjs — do not edit by hand.
 * Image assets as data URIs so PDF export works offline (file:// safe). */
window.IMG = Object.freeze({
${entries.join(",\n")}
});
`;
writeFileSync(join(ROOT, "assets", "img.js"), out);
const kb = (Buffer.byteLength(out) / 1024 / 1024).toFixed(1);
console.log(`\nassets/img.js written — ${entries.length} images, ${kb} MB (${missing} missing)`);
