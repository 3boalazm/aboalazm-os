/**
 * THEME TOKENS — the single source of truth for grounds.
 *
 * Rule from the owner: in dark mode EVERY ground is dark (three dark steps,
 * never a light band); in light mode every ground is light. A "ground" is the
 * surface a whole section stands on. Each ground carries its own surface ramp;
 * text, borders and accent type come from the theme and must clear WCAG AA on
 * every step of every ground — lib/theme-contrast.test.ts enforces that, and
 * also that app/(site)/[locale]/theme-grounds.css is exactly what
 * `groundsCss()` emits, so the CSS cannot drift from the tested values.
 */
export type Rgba = readonly [r: number, g: number, b: number, a?: number];
export type GroundName = "base" | "ink" | "ember" | "glow";

export interface ThemeTokens {
  grounds: Record<GroundName, readonly [s0: string, s1: string, s2: string, s3: string]>;
  text: { primary: Rgba; secondary: Rgba; tertiary: Rgba };
  /** Coloured TYPE (not fills): must reach AA on every ground step. */
  type: { accent: string; lilac: string; mint: string; gold: string };
}

