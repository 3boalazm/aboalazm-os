export const GROUND_NAMES: readonly GroundName[] = ["base", "ink", "ember", "glow"];

export function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace("#", "");
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}
/** Composite a (possibly translucent) colour over an opaque background. */
export function over(fg: Rgba, bg: readonly [number, number, number]): [number, number, number] {
  const a = fg[3] ?? 1;
  const mix = (f: number, b: number) => f * a + b * (1 - a);
  return [mix(fg[0], bg[0]), mix(fg[1], bg[1]), mix(fg[2], bg[2])];
}
function luminance([r, g, b]: readonly [number, number, number]): number {
  const f = (v: number) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}
export function contrast(a: readonly [number, number, number], b: readonly [number, number, number]): number {
  const la = luminance(a);
  const lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

const rgb = (c: Rgba) => `rgb(${c[0]} ${c[1]} ${c[2]} / ${c[3] ?? 1})`;

/** The CSS for theme-grounds.css — generated, never hand-edited. */
export function groundsCss(): string {
  const block = (theme: "dark" | "light") => {
    const t = THEMES[theme];
    const root = theme === "dark" ? ":root" : 'html[data-theme="light"]';
    const lines: string[] = [];
    lines.push(`${root} {`);
    lines.push(`  --color-text-primary: ${rgb(t.text.primary)};`);
    lines.push(`  --color-text-secondary: ${rgb(t.text.secondary)};`);
    lines.push(`  --color-text-tertiary: ${rgb(t.text.tertiary)};`);
    lines.push(`  --color-text-ghost: ${rgb(t.text.tertiary)};`);
    lines.push(`  --color-accent-text: ${t.type.accent};`);
    lines.push(`  --color-lilac-text: ${t.type.lilac};`);
    lines.push(`  --color-mint-text: ${t.type.mint};`);
    lines.push(`  --color-gold-text: ${t.type.gold};`);
    lines.push(`}`);
    for (const name of GROUND_NAMES) {
      const [s0, s1, s2, s3] = t.grounds[name];
      const sel = theme === "dark" ? `.ground-${name}` : `html[data-theme="light"] .ground-${name}`;
      lines.push(`${sel} { --color-surface-0: ${s0}; --color-surface-1: ${s1}; --color-surface-2: ${s2}; --color-surface-3: ${s3}; }`);
    }
    return lines.join("\n");
  };
  return `/* GENERATED by lib/theme-tokens.ts (groundsCss) — edit the tokens, not this block. */\n${block("dark")}\n${block("light")}\n/* END GENERATED */`;
}
