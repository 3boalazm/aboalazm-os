/** Writes the generated token block into theme-grounds.css (between the markers). */
import { readFileSync, writeFileSync } from "node:fs";
import { groundsCss } from "../lib/theme-tokens";

const path = "app/(site)/[locale]/theme-grounds.css";
const css = readFileSync(path, "utf8");
const next = css.replace(/\/\* GENERATED by lib\/theme-tokens\.ts[\s\S]*?\/\* END GENERATED \*\//, groundsCss());
writeFileSync(path, next);
console.log(next === css ? "theme-grounds.css already up to date" : "theme-grounds.css regenerated");
